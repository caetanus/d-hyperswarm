// Generates byte-exact Noise XX handshake vectors from the real noise-handshake
// (dc1f9c4) on the Ed25519 curve. Static AND ephemeral keys are fixed (the
// ephemeral is pre-set on the state, as send() only generates when e === null),
// so the three message bytes and the resulting transport keys are deterministic.
const path = require('path')
const fs = require('fs')

const Noise = require('/home/caetano/lab/noise-handshake/noise')
const curve = require('/home/caetano/lab/noise-curve-ed')

const kp = (b) => curve.generateKeyPair(Buffer.alloc(32, b))
const hex = (b) => Buffer.from(b).toString('hex')

const sInit = kp(1)
const sResp = kp(2)
const eInit = kp(11)
const eResp = kp(12)

const init = new Noise('XX', true, sInit, { curve })
const resp = new Noise('XX', false, sResp, { curve })

init.initialise(Buffer.alloc(0))
resp.initialise(Buffer.alloc(0))

init.e = eInit // fix the ephemeral so the wire is deterministic
resp.e = eResp

// Capture each message's hex IMMEDIATELY: the reference zeroes the ephemeral key
// on the final _clear(), and the message buffer aliases that slab — reading it
// after the handshake would show zeros. (A JS quirk; the D port copies properly.)
const m1 = init.send(Buffer.from('msg1payload'))
const m1hex = hex(m1)
const p1 = resp.recv(m1)
const m2 = resp.send(Buffer.from('msg2payload'))
const m2hex = hex(m2)
const p2 = init.recv(m2)
const m3 = init.send(Buffer.from('msg3payload'))
const m3hex = hex(m3)
const p3 = resp.recv(m3)

// sanity: payloads survive, both sides agree on keys
if (p1.toString() !== 'msg1payload' || p2.toString() !== 'msg2payload' || p3.toString() !== 'msg3payload') {
  throw new Error('payload mismatch')
}
if (!init.tx.equals(resp.rx) || !init.rx.equals(resp.tx) || !init.hash.equals(resp.hash)) {
  throw new Error('key/hash mismatch between sides')
}

const out = [
  ['xx:msg1', m1hex],
  ['xx:msg2', m2hex],
  ['xx:msg3', m3hex],
  ['xx:init-tx', hex(init.tx)],
  ['xx:init-rx', hex(init.rx)],
  ['xx:hash', hex(init.hash)],
  ['xx:rs-init', hex(init.rs)], // responder static, as the initiator learned it
  ['xx:rs-resp', hex(resp.rs)] // initiator static, as the responder learned it
]

let d = '// GENERATED by tests/vectors/noise-hs-gen.js from noise-handshake (XX, Ed25519).\n'
d += '// Fixed static seeds 1/2 and ephemeral seeds 11/12. Do not edit by hand.\n'
d += 'module tests.noise_hs_vectors;\n\n'
d += 'struct HVec { string name; string hex; }\n\n'
d += 'immutable HVec[] noiseHsVectors = [\n'
for (const [n, h] of out) d += `    HVec(${JSON.stringify(n)}, ${JSON.stringify(h)}),\n`
d += '];\n'
fs.writeFileSync(path.join(__dirname, '../noise_hs_vectors.d'), d)
console.log('wrote ' + out.length + ' handshake vectors')
