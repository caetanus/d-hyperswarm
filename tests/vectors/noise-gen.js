// Generates byte-exact vectors for the Noise crypto primitives from the real JS
// (noise-handshake dc1f9c4 + noise-curve-ed e8265e7, cloned as siblings under
// ~/lab). Emits a D module the test asserts against. Case names match the D test.
const path = require('path')
const fs = require('fs')

const NH = '/home/caetano/lab/noise-handshake'
const hmac = require(path.join(NH, 'hmac'))
const { hkdf } = require(path.join(NH, 'hkdf'))
const CipherState = require(path.join(NH, 'cipher'))
const curve = require('/home/caetano/lab/noise-curve-ed')

const out = []
const hex = (b) => Buffer.from(b).toString('hex')

// HMAC-BLAKE2b: key, message -> 64-byte tag
function hmacCase (name, key, msg) {
  const o = Buffer.alloc(64)
  hmac(o, [Buffer.from(msg)], Buffer.from(key))
  out.push([name, hex(o)])
}
hmacCase('hmac:short', 'key', 'abc')
hmacCase('hmac:empty-msg', 'salt', '')
hmacCase('hmac:longkey', 'k'.repeat(200), 'message') // >BLOCKLEN → key is hashed

// HKDF: salt, ikm -> block0 || block1 (each 64 bytes)
function hkdfCase (name, salt, ikm) {
  const [a, b] = hkdf(Buffer.from(salt), Buffer.from(ikm))
  out.push([name, hex(a) + hex(b)])
}
hkdfCase('hkdf:basic', 'salt', 'ikm')
hkdfCase('hkdf:empty-ikm', 'chaining', '')

// ChaCha20-Poly1305 IETF: key(32 × byte), counter, ad, plaintext -> ciphertext
function cipherCase (name, keyByte, counter, ad, pt) {
  const c = new CipherState(Buffer.alloc(32, keyByte))
  c.nonce = counter
  const ct = c.encrypt(Buffer.from(pt), Buffer.from(ad))
  out.push([name, hex(ct)])
}
cipherCase('cipher:c0-noad', 1, 0, Buffer.alloc(0), 'hello')
cipherCase('cipher:c5-ad', 2, 5, Buffer.from([0xaa, 0xbb, 0xcc]), 'payload data')

// Ed25519 DH: two seeds -> the public keys and dh(pubB, keypairA)
{
  const kpA = curve.generateKeyPair(Buffer.alloc(32, 3))
  const kpB = curve.generateKeyPair(Buffer.alloc(32, 9))
  out.push(['dh:pkA', hex(kpA.publicKey)])
  out.push(['dh:pkB', hex(kpB.publicKey)])
  out.push(['dh:shared', hex(curve.dh(kpB.publicKey, kpA))])
}

let d = '// GENERATED by tests/vectors/noise-gen.js from noise-handshake + noise-curve-ed.\n'
d += '// Do not edit by hand.\n'
d += 'module tests.noise_crypto_vectors;\n\n'
d += 'struct NVec { string name; string hex; }\n\n'
d += 'immutable NVec[] noiseCryptoVectors = [\n'
for (const [n, h] of out) d += `    NVec(${JSON.stringify(n)}, ${JSON.stringify(h)}),\n`
d += '];\n'
fs.writeFileSync(path.join(__dirname, '../noise_crypto_vectors.d'), d)
console.log('wrote ' + out.length + ' vectors')
